"""Chapter 21: stopping counterexample and component arithmetic, not NUTS."""

import math
import random
from collections.abc import Sequence


def relative_weights(energies: Sequence[float]) -> list[float]:
    """Rescale finite energies; tiny relative weights may underflow to zero."""
    if not energies or any(not math.isfinite(value) for value in energies):
        raise ValueError("Provide a nonempty sequence of finite energies")
    offset = min(energies)
    return [math.exp(-(value - offset)) for value in energies]


def reservoir(weights: Sequence[float], rng: random.Random) -> int:
    """Sample represented nonnegative weights with a positive finite total."""
    if not weights or any(not math.isfinite(w) or w < 0 for w in weights):
        raise ValueError("Provide finite, nonnegative weights")
    total = sum(weights)
    if not math.isfinite(total) or total <= 0:
        raise ValueError("Total weight must be positive and finite")
    representative = next(i for i, weight in enumerate(weights) if weight > 0)
    weight_total = weights[representative]
    for label in range(representative + 1, len(weights)):
        weight = weights[label]
        if weight == 0:
            continue
        weight_total += weight
        if rng.random() < weight / weight_total:
            representative = label
    return representative


def first_extremum(position: float, momentum: float) -> float:
    """Exact Gaussian turning point; deliberately INVALID as an HMC update."""
    if not math.isfinite(position) or not math.isfinite(momentum) or momentum == 0:
        raise ValueError("Provide finite position and finite nonzero momentum")
    return math.copysign(math.hypot(position, momentum), momentum)


def dual_averaging_trace(
    acceptance_stats: Sequence[float], initial_step: float = 0.1, target: float = 0.8
) -> list[tuple[float, float, float]]:
    """Return (mean error, next step, smoothed step) for one teaching interval.

    Uses gamma=.05, t0=10, kappa=.75. Statistics are supplied, not generated by
    NUTS; there are no metric updates or restarts in this isolated controller.
    """
    if not acceptance_stats or any(
        not math.isfinite(value) or not 0 <= value <= 1
        for value in acceptance_stats
    ):
        raise ValueError("Provide a nonempty sequence of statistics in [0, 1]")
    if not math.isfinite(initial_step) or initial_step <= 0:
        raise ValueError("Initial step must be finite and positive")
    if not math.isfinite(target) or not 0 < target < 1:
        raise ValueError("Target must be finite and strictly between zero and one")
    mu = math.log(initial_step) + math.log(10)
    mean_error = 0.0
    log_average = 0.0
    trace = []
    for iteration, statistic in enumerate(acceptance_stats, start=1):
        learning_rate = 1 / (iteration + 10)
        mean_error = ((1 - learning_rate) * mean_error
                      + learning_rate * (target - statistic))
        log_step = mu - math.sqrt(iteration) * mean_error / 0.05
        smoothing_weight = iteration ** (-0.75)
        log_average = (smoothing_weight * log_step
                       + (1 - smoothing_weight) * log_average)
        trace.append((mean_error, math.exp(log_step), math.exp(log_average)))
    return trace


def main() -> None:
    print("Exact oscillator: q(0)=0, p(0)=1; these are not NUTS draws")
    print("time/pi       q           p       displacement * p")
    for fraction in (0.25, 0.5, 0.75, 2.0):
        time = fraction * math.pi
        position, momentum = math.sin(time), math.cos(time)
        print(f"{fraction:7.2f}  {position:10.6f}  {momentum:10.6f}  "
              f"{position * momentum:16.6f}")

    counterexample_rng = random.Random(21022)
    repetitions = 40_000
    initial_squares = []
    stopped_squares = []
    for _ in range(repetitions):
        position = counterexample_rng.gauss(0, 1)
        momentum = counterexample_rng.gauss(0, 1)
        while momentum == 0:  # The exact zero-momentum case is outside the rule.
            momentum = counterexample_rng.gauss(0, 1)
        stopped = first_extremum(position, momentum)
        initial_squares.append(position * position)
        stopped_squares.append(stopped * stopped)
    print(f"\nINVALID stop-at-extremum rule: {repetitions} independent inputs, seed=21022")
    print(f"Initial E[q^2]: empirical {sum(initial_squares) / repetitions:.6f}, exact 1")
    print(f"Stopped E[q^2]: empirical {sum(stopped_squares) / repetitions:.6f}, exact 2")
    print(f"Stopped second-moment standard error: {2 / math.sqrt(repetitions):.6f}")
    print("Exact energy conservation does not make this stopped map valid HMC.")

    acceptance_stats = (0.6, 0.7, 0.9, 0.8)
    print("\nDual averaging with supplied hypothetical statistics; no sampler is run")
    print("update  statistic  mean error   next step   smoothed step")
    for iteration, (error, next_step, smoothed_step) in enumerate(
        dual_averaging_trace(acceptance_stats), start=1
    ):
        print(f"{iteration:6d}  {acceptance_stats[iteration - 1]:9.1f}  {error:10.6f}"
              f"  {next_step:10.6f}  {smoothed_step:13.6f}")

    rng = random.Random(21021)
    repetitions = 60_000
    weights = relative_weights((0.0, math.log(2.0), math.log(4.0)))
    total = sum(weights)
    counts = [0] * len(weights)
    for _ in range(repetitions):
        counts[reservoir(weights, rng)] += 1
    print(f"\nIndependent reservoir experiments: {repetitions}, seed=21021")
    print("label  theoretical   empirical   marginal standard error")
    for label, weight in enumerate(weights):
        probability = weight / total
        standard_error = math.sqrt(probability * (1 - probability) / repetitions)
        print(f"{label:5d}  {probability:11.6f}  "
              f"{counts[label] / repetitions:10.6f}  {standard_error:23.6f}")
    print("\nOld/new component weights 6 and 2:")
    print(f"Unbiased merge replacement: {2 / (6 + 2):.6f}")
    print(f"Biased progressive replacement: {min(1.0, 2 / 6):.6f}")
    print("Only the unbiased reservoir identity is simulated above.")
    tiny_weights = relative_weights((1000.0, 0.0, 1000.0))
    print(f"\nUnderflow example: represented weights {tiny_weights}, "
          f"selected label {reservoir(tiny_weights, rng)}")
    print("No trajectory construction or MCMC convergence claim is made.")


if __name__ == "__main__":
    main()
