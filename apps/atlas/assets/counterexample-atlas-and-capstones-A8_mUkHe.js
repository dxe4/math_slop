<details><summary>Solution</summary>

#### ANA-CH22-E018 — Solution

For \\(n\\ge 2\\), set
\\(f_n(x)=\\max(1-2n^2|x-1/n|,0)\\); define the irrelevant first term to be zero.
This is a triangular spike of height one centered at \\(1/n\\) whose full base of
width \\(1/n^2\\) lies inside \\([0,1]\\). Its integral is \\(1/(2n^2)\\to 0\\), while its
supremum is one. Zero never belongs to the support, and every fixed positive
\\(x\\) is outside the support for all sufficiently large \\(n\\), so convergence is
pointwise to zero.

</details>

